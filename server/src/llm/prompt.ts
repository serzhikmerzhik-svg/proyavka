/** Текстовая часть сообщения пользователя (кадры идут перед ней отдельными блоками). */
export function buildUserText(req: AnalyzeRequest): string {
  const s = req.song;
  const songMeta = [s.year, s.genre].filter(Boolean).join(', ');
  const frames = req.photos.length
    ? `Кадров: ${req.photos.length} (выше по порядку: ${req.photos.map((_, i) => `Кадр ${i}`).join(', ')}).`
    : 'Фото к анализу не приложены.';
  return [
    `Дата: ${req.date}.`,
    `Песня дня: ${s.artist} — ${s.title}${songMeta ? ` (${songMeta})` : ''}.`,
    frames,
    '',
    '<текст_дня>',
    req.text,
    '</текст_дня>',
  ].join('\n');
}

